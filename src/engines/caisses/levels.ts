/** Scenes of « Les caisses de Boubou ». Each level is a short scene written by hand: a title Boubou says, one strong moment
 * that no other scene repeats, and the garden, one string per row from the top. One character per cell:
 *   `.` grass   `@` Boubou   `#` a stone wall   `*` a bush   `~` the pond   `X` a hole   `=` ice   `→ ← ↑ ↓` a belt
 *   `_` the big button       `D` the gate, open while a crate sits on the button
 *   crates, each with its toy and its colour: `b` balloon (red)  `o` teddy bear (orange)  `v` car (blue)  `e` star (yellow)
 *                                             `g` frog (green)
 *   spots: `+` any crate fits; `B O V E G` the spot drawn with that toy, for that crate only
 * New things come one at a time, each alone in a scene before they are combined. `problems()` in index.ts and
 * tests/caisses.test.ts check every rule. The list is final: it never changes under a player. */
export const features = ['tirer', 'motif', 'eau', 'tapis', 'porte', 'glace', 'trou'] as const;
export type Feature = typeof features[number];
export const motifs = ['ballon', 'ours', 'voiture', 'etoile', 'grenouille'] as const;
export type Motif = typeof motifs[number];
export const MOTIF_LETTERS: readonly (readonly [string, Motif])[] = [['b', 'ballon'], ['o', 'ours'], ['v', 'voiture'], ['e', 'etoile'], ['g', 'grenouille']];
