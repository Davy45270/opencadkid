/** Scenes of « Les surprises de Tutu ». Each level is a short scene written by hand: a title Tutu says, one strong moment no
 * other scene repeats (most often a shape the cartons draw), the yard, one string per row from the top, and the friends who
 * walk their round. One character per cell:
 *   `.` the yard   `@` Tutu   `#` a brick wall (it stops the confetti)   `*` a flower bed (Tutu never walks on it, the
 *   confetti fly over it)   `→ ← ↑ ↓` a fan (a box put on it is blown one cell that way)
 *   `g` the big box (picked up, the confetti fly one cell further)   `m` one box more (two boxes in the pocket)
 *   cartons: `c` empty (a clown on a spring says « coucou »), `p` apples, `k` a kitten, `b` balloons, `o` a teddy bear;
 *   the same letter in capitals is a double carton, opened by two confetti.
 * A friend starts on cell (x, y) and walks its round, one letter per step (`h` up, `b` down, `g` left, `d` right), back to
 * where it started. New things come one at a time, each alone in a scene before they are combined. `problems()` in index.ts
 * and tests/cartons.test.ts check every rule. The list is final: it never changes under a player. */
