/** Scenes of « La chenille de Lumi ». Each level is a short scene written by hand: a title Lumi says, one strong moment that
 * no other scene repeats, the garden (one string per row from the top) and the caterpillar. One character per cell:
 *   `.` grass   `#` a hedge   `o` a stone   `~` a puddle   `f` a flower (smelt, never eaten)   `C` the cocoon
 *   `@` the head of the caterpillar; `tail` lists, from the head, the way each next ring lies (`h` up, `b` down,
 *       `g` left, `d` right), always on grass
 *   food: `l` a leaf (one ring more)   `s` a sweet leaf (two rings more)   `p` an apple (one ring less, never required)
 *         `1` to `6` leaves of the colours of the rainbow (red, orange, yellow, green, blue, purple), eaten in that order
 *   `U` the two holes of a tunnel: in one, out of the other   `H` a bridge: the caterpillar may cross over itself there
 * The cocoon opens once every leaf is eaten. New things come one at a time, each alone in a scene before they are
 * combined. `problems()` in index.ts and tests/chenille.test.ts check every rule. The list is final: it never changes under
 * a player. */
