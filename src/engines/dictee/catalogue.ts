/** The word catalogue of the dictation: a versioned JSON contract, its checks, and what the child may see.
 * A word reaches the child only once an adult has reviewed it (`contentStatus: 'reviewed'`, `validatedBy` set) and it
 * passes every check; a homophone without a context sentence is never publishable. */

export const grades = ['CP', 'CE1', 'CE2', 'CM1', 'CM2'] as const;
export type Grade = typeof grades[number];
export type ContentStatus = 'draft' | 'reviewed';
export interface Word {
    id: string;
    lemma: string;
    /** The exact spelling the child must write. */
    expectedForm: string;
    grade: Grade;
    tags: string[];
    /** Other words heard the same way (vert, verre, ver, vers). */
    homophones: string[];
    contextSentence: string | null;
    /** One line, for a child, on how to remember the spelling. */
    explanation: string | null;
    /** Audio files next to the page, pre-generated by a local voice at build time. */
    pronunciationAsset: string;
    contextAsset: string | null;
    difficulty: number;
    contentStatus: ContentStatus;
    validatedBy: string | null;
    version: number;
}
export interface Catalogue { schemaVersion: '1.0'; version: number; locale: 'fr-FR'; words: Word[] }

const isText = (x: unknown): x is string => typeof x === 'string' && x.trim().length > 0;
const textOrNull = (x: unknown): x is string | null => x === null || isText(x);

/** Reads the catalogue JSON; an entry that does not follow the contract is dropped, never shown. */
export function parseCatalogue(data: unknown): Catalogue {
    const empty: Catalogue = { schemaVersion: '1.0', version: 0, locale: 'fr-FR', words: [] };
    if (!data || typeof data !== 'object') return empty;
    const c = data as Record<string, unknown>;
    if (c.schemaVersion !== '1.0' || !Array.isArray(c.words) || typeof c.version !== 'number') return empty;
    const words: Word[] = [];
    for (const raw of c.words) {
        if (!raw || typeof raw !== 'object') continue;
        const w = raw as Record<string, unknown>;
        if (!isText(w.id) || !isText(w.lemma) || !isText(w.expectedForm) || !grades.includes(w.grade as Grade)) continue;
        if (!Array.isArray(w.tags) || !w.tags.every(isText) || !Array.isArray(w.homophones) || !w.homophones.every(isText)) continue;
        if (!textOrNull(w.contextSentence) || !textOrNull(w.explanation) || !isText(w.pronunciationAsset) || !textOrNull(w.contextAsset)) continue;
        if (typeof w.difficulty !== 'number' || (w.contentStatus !== 'draft' && w.contentStatus !== 'reviewed') || !textOrNull(w.validatedBy) || typeof w.version !== 'number') continue;
        words.push({ id: w.id, lemma: w.lemma, expectedForm: w.expectedForm.normalize('NFC'), grade: w.grade as Grade, tags: [...w.tags], homophones: [...w.homophones],
            contextSentence: w.contextSentence, explanation: w.explanation, pronunciationAsset: w.pronunciationAsset, contextAsset: w.contextAsset,
            difficulty: w.difficulty, contentStatus: w.contentStatus, validatedBy: w.validatedBy, version: w.version });
    }
    return { schemaVersion: '1.0', version: c.version, locale: 'fr-FR', words };
}

/** What stops a word from being published. Empty means publishable once reviewed. */
export function problems(w: Word): string[] {
    const p: string[] = [];
    if (w.expectedForm !== w.expectedForm.normalize('NFC') || w.expectedForm !== w.expectedForm.trim()) p.push('forme non normalisée');
    if (w.homophones.length && !w.contextSentence) p.push('homophone sans phrase de contexte');
    if (w.contextSentence && !w.contextSentence.toLowerCase().split(/[^\p{L}-]+/u).includes(w.expectedForm.toLowerCase())) p.push('la phrase ne contient pas le mot');
    if (w.contextSentence && !w.contextAsset) p.push('phrase sans audio');
    if (w.explanation && w.explanation.includes('\n')) p.push('explication sur plusieurs lignes');
    if (w.contentStatus === 'reviewed' && !w.validatedBy) p.push('relu sans nom de relecteur');
    return p;
}
export const publishable = (w: Word): boolean => w.contentStatus === 'reviewed' && w.validatedBy !== null && problems(w).length === 0;
/** The words of a grade the child may see: reviewed ones only, unless drafts are shown on purpose (development). */
export function playable(c: Catalogue, grade: Grade, drafts = false): Word[] {
    return c.words.filter(w => w.grade === grade && (publishable(w) || (drafts && problems(w).length === 0)));
}
