/** The word catalogue of the dictation: a versioned JSON contract (schema 1.1), its checks, and what the child may see.
 * A word reaches the child only once an adult has approved it: `status: 'approved'`, `validatedBy` set, the four
 * reviews (spelling, teaching, context sentence, audio) approved, and every check passed. A homophone without a context
 * sentence is never publishable, and a word whose recording waits for a human ear (`audio.mode: 'audio_manual_review'`)
 * neither. */

export const grades = ['CP', 'CE1', 'CE2', 'CM1', 'CM2'] as const;
export type Grade = typeof grades[number];
export const statuses = ['draft', 'needs_review', 'approved', 'rejected'] as const;
export type Status = typeof statuses[number];
/** How the word is said: alone; alone then its sentence; always with its sentence (the sound alone is ambiguous: verre,
 * vert, vers); or not yet, the recording waits for an adult to listen to it. */
export const audioModes = ['word_only', 'word_then_context', 'context_required', 'audio_manual_review'] as const;
export type AudioMode = typeof audioModes[number];
export const reviewKeys = ['orthography', 'pedagogy', 'context', 'audio'] as const;
export type ReviewState = 'pending' | 'approved' | 'rejected';
export type Review = Record<typeof reviewKeys[number], ReviewState>;
export interface Word {
    id: string;
    lemma: string;
    /** The exact spelling the child must write. */
    expectedForm: string;
    grade: Grade;
    tags: string[];
    /** Other words heard the same way (vert, verre, ver, vers). */
    homophones: string[];
    /** A note on a homophone that is not heard the same by everyone (pensée, penser). */
    homophoneNotes: Record<string, string>;
    contextSentence: string | null;
    /** One line, for a child, on how to remember the spelling. */
    explanation: string | null;
    /** Audio files next to the page, pre-generated by a local voice at build time. */
    pronunciationAsset: string;
    contextAsset: string | null;
    /** The versions (text, voice and engine fingerprints) of the two recordings. */
    audio: { mode: AudioMode; wordVersion?: string | null; contextVersion?: string | null; wordSha256?: string | null; contextSha256?: string | null };
    difficulty: number;
    status: Status;
    review: Review;
    validatedBy: string | null;
    version: number;
}
export interface Catalogue { schemaVersion: '1.1'; version: number; locale: 'fr-FR'; words: Word[] }

const isText = (x: unknown): x is string => typeof x === 'string' && x.trim().length > 0;
const textOrNull = (x: unknown): x is string | null => x === null || isText(x);

const reviewState = (x: unknown): x is ReviewState => x === 'pending' || x === 'approved' || x === 'rejected';

/** Reads the catalogue JSON; an entry that does not follow the contract is dropped, never shown. */
export function parseCatalogue(data: unknown): Catalogue {
    const empty: Catalogue = { schemaVersion: '1.1', version: 0, locale: 'fr-FR', words: [] };
    if (!data || typeof data !== 'object') return empty;
    const c = data as Record<string, unknown>;
    if (c.schemaVersion !== '1.1' || !Array.isArray(c.words) || typeof c.version !== 'number') return empty;
    const words: Word[] = [];
    for (const raw of c.words) {
        if (!raw || typeof raw !== 'object') continue;
        const w = raw as Record<string, unknown>;
        if (!isText(w.id) || !isText(w.lemma) || !isText(w.expectedForm) || !grades.includes(w.grade as Grade)) continue;
        if (!Array.isArray(w.tags) || !w.tags.every(isText) || !Array.isArray(w.homophones) || !w.homophones.every(isText)) continue;
        if (!textOrNull(w.contextSentence) || !textOrNull(w.explanation) || !isText(w.pronunciationAsset) || !textOrNull(w.contextAsset)) continue;
        if (typeof w.difficulty !== 'number' || !statuses.includes(w.status as Status) || !textOrNull(w.validatedBy) || typeof w.version !== 'number') continue;
        const audio = w.audio as Record<string, unknown> | undefined;
        if (!audio || !audioModes.includes(audio.mode as AudioMode)) continue;
        const review = w.review as Record<string, unknown> | undefined;
        if (!review || !reviewKeys.every(k => reviewState(review[k]))) continue;
        const notes = w.homophoneNotes ?? {};
        if (typeof notes !== 'object' || !Object.values(notes).every(isText)) continue;
        words.push({ id: w.id, lemma: w.lemma, expectedForm: w.expectedForm.normalize('NFC'), grade: w.grade as Grade, tags: [...w.tags], homophones: [...w.homophones],
            homophoneNotes: { ...(notes as Record<string, string>) }, contextSentence: w.contextSentence, explanation: w.explanation,
            pronunciationAsset: w.pronunciationAsset, contextAsset: w.contextAsset, audio: { mode: audio.mode as AudioMode, wordVersion: typeof audio.wordVersion === 'string' ? audio.wordVersion : null, contextVersion: typeof audio.contextVersion === 'string' ? audio.contextVersion : null, wordSha256: typeof audio.wordSha256 === 'string' ? audio.wordSha256 : null, contextSha256: typeof audio.contextSha256 === 'string' ? audio.contextSha256 : null }, difficulty: w.difficulty,
            status: w.status as Status, review: Object.fromEntries(reviewKeys.map(k => [k, review[k]])) as Review, validatedBy: w.validatedBy, version: w.version });
    }
    return { schemaVersion: '1.1', version: c.version, locale: 'fr-FR', words };
}

/** What stops a word from being published. Empty means publishable once reviewed. */
export function problems(w: Word): string[] {
    const p: string[] = [];
    if (w.expectedForm !== w.expectedForm.normalize('NFC') || w.expectedForm !== w.expectedForm.trim()) p.push('forme non normalisée');
    if (w.homophones.length && !w.contextSentence) p.push('homophone sans phrase de contexte');
    // A hyphenated word counts whole and by its parts (« ce jour-là » holds « jour »).
    if (w.contextSentence && !w.contextSentence.toLowerCase().split(/[^\p{L}-]+/u).flatMap(x => [x, ...x.split('-')]).includes(w.expectedForm.toLowerCase())) p.push('la phrase ne contient pas le mot');
    if (w.contextSentence && !w.contextAsset) p.push('phrase sans audio');
    if (w.explanation && w.explanation.includes('\n')) p.push('explication sur plusieurs lignes');
    if (w.audio.mode === 'context_required' && !(w.contextSentence && w.contextAsset)) p.push('phrase obligatoire absente');
    if (w.audio.mode === 'audio_manual_review') p.push('audio à écouter par un adulte');
    if (w.status === 'approved' && !w.validatedBy) p.push('approuvé sans nom de relecteur');
    if (w.status === 'approved' && !reviewKeys.every(k => w.review[k] === 'approved')) p.push('approuvé sans les quatre relectures');
    return p;
}
/** Only an approved word, with its four reviews and no problem, ever reaches a child. */
export const publishable = (w: Word): boolean => w.status === 'approved' && w.validatedBy !== null && reviewKeys.every(k => w.review[k] === 'approved') && problems(w).length === 0;
/** The words of a grade the child may see: approved ones only. A development server started on purpose shows the
 * drafts and words waiting for review too (never a rejected one), to try them. */
export function playable(c: Catalogue, grade: Grade, drafts = false): Word[] {
    return c.words.filter(w => w.grade === grade && (publishable(w) || (drafts && w.status !== 'rejected' && w.audio.mode !== 'audio_manual_review' && problems(w).length === 0)));
}
/** Whether the sentence is said on the card's arrival, after the word. */
export const sentenceOnArrival = (w: Word): boolean => (w.audio.mode === 'context_required' || w.audio.mode === 'word_then_context') && w.contextAsset !== null;
