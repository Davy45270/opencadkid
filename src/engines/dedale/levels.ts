/** Scenes of « Le jardin de Boubou ». Each level is a short scene written by hand: a title Boubou says, one strong moment
 * that no other scene repeats (most often a shape the hedges draw), the garden, one string per row from the top, and the
 * friends who walk their round. One character per cell:
 *   `.` a path   `#` a hedge   `@` Boubou   `*` a seed   `S` a sun   `k` the key flower   `D` a garden gate
 *   `o` a puddle   `~` the stream   `-` a bridge crossed left-right   `|` a bridge crossed up-down
 *   `=` a tunnel mouth (it comes out at the mouth on the other edge)   `f` a carpet of leaves
 * A friend starts on cell (x, y) and walks its round, one letter per step (`h` up, `b` down, `g` left, `d` right), back to
 * where it started. New things come one at a time, each alone in a scene (with only what it needs) before they are combined.
 * `problems()` in index.ts and tests/dedale.test.ts check every rule. The list is final: it never changes under a player. */
export const features = ['papillon', 'flaque', 'herisson', 'soleil', 'coccinelle', 'porte', 'tunnel', 'pont', 'feuilles'] as const;
export type Feature = typeof features[number];
export const friendKinds = ['papillon', 'herisson', 'coccinelle'] as const;
export type FriendKind = typeof friendKinds[number];
export interface Friend { kind: FriendKind; x: number; y: number; route: string }
export interface LevelDef { id: number; title: { fr: string; en: string }; moment: string; rows: readonly string[]; friends: readonly Friend[] }
